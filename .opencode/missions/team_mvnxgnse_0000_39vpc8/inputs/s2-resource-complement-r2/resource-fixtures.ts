function stamp<T extends { fingerprint: string }>(value: T): T {
  const { fingerprint: _old, ...content } = value;
  return { ...value, fingerprint: digest(content) };
}
export function requirement(): ResourceRequirement {
  return { profiles: ["author", "reviewer"], models: ["alias", "primary"], tools: [], accounts: ["shared"], slots: 1, cpu: 2, gpu: 1, budget: 3 };
}

/** No seal/bind/plan/selection is called. Parent must later validate/scelle this
 * NEW source under a separate gate. Rebuild all affected refs/joins explicitly.
 */
export function createResourceCompleteInput(cap = 100000): AuthorFixture {
  const f = fixture({ cap, rootCap: 100000 });
  const template = decoded<GraphExecutionTemplate>(f.body.admissionSource.executionTemplate);
  template.settings.maxConcurrent = 3;
  template.workers = [
    { workerId: "worker-a", profile: "author", model: "primary", tools: [], accountId: "shared", slots: 4, cpu: 8, gpu: 3, budget: 10, available: true },
    { workerId: "worker-b", profile: "author", model: "alias", tools: [], accountId: "shared", slots: 4, cpu: 8, gpu: 3, budget: 10, available: true },
  ];
  template.accounts = [{ accountId: "shared", slots: 4, budget: 10 }];
  const templateDoc = document("l8-execution-template-v1", template);
  const spec = decoded<GraphExecutionSource>(f.body.admissionSource.executionSourceSpec);
  spec.templateFingerprint = digest(template);
  const specDoc = document("l8-execution-source-v1", spec);
  const context = { ...f.body.admissionSource.context, executionSpecFingerprint: digest(spec) };
  const policy = structuredClone(f.policy);
  policy.resourcesByFunction = { [functionId]: requirement() };
  if (!policy.admissionBudget) throw new Error("explicit author allocation missing");
  policy.admissionBudget = stamp({ ...policy.admissionBudget, context });
  const planning = decoded<PlannerResult>(f.body.planning), unitId = planning.units[0]!.unitId;
  // Single function: the manually specified unit requirement is exactly the
  // intersection/max/sum contract, not a result generated by a planner helper.
  const planId = `plan:${digest({ snapshot: f.snapshot.normalizedFingerprint, policy, families: [[functionId]],
    relationViewVersion: "planner-relations-v1", relationPolicyVersion: "planner-relation-policy-v2",
    admissionAccountingVersion: "planner-admission-accounting-v1", admissionBudgetContext: context })}`;
  planning.plan = stamp({ ...planning.plan, planId });
  if (!planning.sidecar.admissionBudget) throw new Error("explicit author budget sidecar missing");
  planning.sidecar = stamp({ ...planning.sidecar, planId, planFingerprint: planning.plan.fingerprint, policy,
    resourcesByUnit: { [unitId]: requirement() },
    admissionBudget: { ...planning.sidecar.admissionBudget, context, allocationFingerprint: policy.admissionBudget.fingerprint } });
  planning.binding = stamp({ ...planning.binding, planFingerprint: planning.plan.fingerprint, sidecarFingerprint: planning.sidecar.fingerprint });
  const planningDoc = document("l8-planning-source-v1", planning), policyDoc = document("l8-planning-policy-source-v1", policy);
  const root = decoded<RootLimitsV1>(f.body.admissionSource.budgetLineage.rootLimits);
  const allocationDoc = document("l8-admission-allocation-source-v1", policy.admissionBudget);
  const rootAccountId = valueDigest("l8-budget-root-v1", { missionId: f.body.missionId, lineageId: f.body.generation.lineageId, rootAllocationRef: allocationDoc.ref });
  if (!root.rootSlotGrants || !root.rootModelBindings || !f.body.rootBootstrapSources) throw new Error("explicit author root sources missing");
  const grants = decoded<RootSlotGrantsV1>(root.rootSlotGrants);
  grants.rootAccountId = rootAccountId; grants.rootAllocationRef = allocationDoc.ref;
  grants.sourcePlanningRef = planningDoc.ref; grants.sourcePolicyRef = policyDoc.ref;
  grants.grants = grants.grants.map(g => ({ ...g, slot: { ...g.slot, rootAccountId } }));
  const bindings = decoded<RootModelBindingsV1>(root.rootModelBindings);
  bindings.sourceExecutionTemplateRef = templateDoc.ref; bindings.sourceExecutionSpecRef = specDoc.ref;
  bindings.rootAccountId = rootAccountId;
  // Preserve primary/alias -> SAME Model.Ref, including roleLabels.B=alias.
  root.allocation = allocationDoc; root.executionTemplate = templateDoc;
  root.rootSlotGrants = document(root.rootSlotGrants.ref.kind, grants);
  root.rootModelBindings = document(root.rootModelBindings.ref.kind, bindings);
  const rootDoc = document("l8-root-limits-v1", root);
  const bootstrap = { ...f.body.rootBootstrapSources, executionTemplate: templateDoc, executionSourceSpec: specDoc,
    planning: planningDoc, planningPolicy: policyDoc };
  f.body.planning = planningDoc; f.body.planningPolicy = policyDoc; f.body.rootBootstrapSources = bootstrap;
  Object.assign(f.body.admissionSource, { executionTemplate: templateDoc, executionSourceSpec: specDoc, context,
    allocation: structuredClone(policy.admissionBudget), budgetLineage: { ...f.body.admissionSource.budgetLineage,
      rootAccountId, rootAllocationRef: allocationDoc.ref, rootLimits: rootDoc },
    sourceFingerprints: { ...f.body.admissionSource.sourceFingerprints, executionTemplate: digest(template),
      executionSourceSpec: digest(spec), context: digest(context), allocation: policy.admissionBudget.fingerprint } });
  Object.assign(f.body.preparationObservationT0, { rootLimitsRef: rootDoc.ref,
    rootSlotGrantsRef: root.rootSlotGrants.ref, rootModelBindingsRef: root.rootModelBindings.ref });
  Object.assign(f.independent, { executionTemplate: structuredClone(templateDoc), executionSourceSpec: structuredClone(specDoc),
    rootLimits: structuredClone(rootDoc), rootBootstrapSources: structuredClone(bootstrap), planningPolicy: structuredClone(policyDoc) });
  f.policy = structuredClone(policy);
  return f;
}

